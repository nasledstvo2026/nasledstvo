# ---------- Листы по группам ----------
def group_sheet(title, gr_key):
    wsg = wb.create_sheet(title.replace('Группа ', ''))
    style_header(wsg, ["№", "Мера", "Размер (2026)", "Периодичность", "Условия предоставления", "Нормативный акт-основание"])
    n = 0
    for i, r in enumerate(rows, 1):
        if gr_key in gmap.get(i, set()):
            n += 1
            vals = [n, r["name"], r["size"], r["per"], r["cond"], r["npa"]]
            for c, v in enumerate(vals, 1):
                cell = wsg.cell(row=n+1, column=c, value=v)
                cell.alignment = wrap; cell.border = border; cell.font = Font(size=9)
    for col, w in zip("ABCDEF", [5, 46, 34, 16, 44, 40]):
        wsg.column_dimensions[col].width = w
    wsg.freeze_panes = "A2"
    return n

