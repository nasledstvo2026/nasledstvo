def set_run(r, bold=False):
    r.font.name = FONT
    r.font.size = SIZE
    r.bold = bold
    rr = r._element.get_or_add_rPr()
    rfonts = rr.get_or_add_rFonts()
    for a in ('w:ascii', 'w:hAnsi', 'w:cs'):
        rfonts.set(qn(a), FONT)


def para(text='', align=WD_ALIGN_PARAGRAPH.JUSTIFY, indent=True, bold=False):
    p = doc.add_paragraph()
    p.alignment = align
    p.paragraph_format.line_spacing = 1.5
    if indent:
        p.paragraph_format.first_line_indent = Cm(1.25)
    if text:
        set_run(p.add_run(text), bold)
    return p


def heading(text):
    return para(text, align=WD_ALIGN_PARAGRAPH.CENTER, indent=False, bold=True)


def add_page_field(p):
    run = p.add_run()
    set_run(run)
    f1 = OxmlElement('w:fldChar'); f1.set(qn('w:fldCharType'), 'begin')
    it = OxmlElement('w:instrText'); it.set(qn('xml:space'), 'preserve'); it.text = 'PAGE'
    f2 = OxmlElement('w:fldChar'); f2.set(qn('w:fldCharType'), 'end')
    run._r.append(f1); run._r.append(it); run._r.append(f2)


